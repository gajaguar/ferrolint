/// The version of the `ferrolint:plugin` WIT contract this SDK implements.
pub const CONTRACT_VERSION: &str = env!("CARGO_PKG_VERSION");

/// The raw bindings of the `ferrolint:plugin` WIT contract.
// Generated by wit-bindgen, so its style is not this crate's to lint.
#[allow(clippy::all, clippy::pedantic)]
pub mod bindings {
    wit_bindgen::generate!({
        path: "../../wit",
        world: "plugin",
        pub_export_macro: true,
        default_bindings_module: "ferrolint_plugin_sdk::bindings",
        additional_derives: [PartialEq, Eq],
    });
}

/// A plugin: its rules and what it does on each visitor event. The host
/// makes a fresh `Default` value for every file.
pub trait Checker: Default {
    /// The plugin's name, version and rules.
    fn info() -> Info;

    /// Called once per file, before the first node.
    fn start_file(&mut self, _cx: &mut Context<'_>) {}

    /// Called for each node in source order, parents before children.
    fn visit(&mut self, _node: &Node, _cx: &mut Context<'_>) {}

    /// Called after the node's last descendant.
    fn leave(&mut self, _node: &Node, _cx: &mut Context<'_>) {}

    /// Called once per file, after the last node.
    fn end_file(&mut self, _cx: &mut Context<'_>) {}
}

/// Run a checker over one file: the visitor events in order, then the
/// diagnostics it reported.
/// A diagnostic without a severity gets its rule's.
pub fn run<C: Checker>(file: &File, nodes: &[Node], semantic: &dyn Semantic) -> Vec<Diagnostic> {
    let rules = C::info().rules;
    let mut checker = C::default();
    let mut cx = Context::new(file, nodes, semantic);
    checker.start_file(&mut cx);
    let mut open: Vec<&Node> = Vec::new();
    for node in nodes {
        while let Some(top) = open.pop_if(|top| top.last < node.id) {
            checker.leave(top, &mut cx);
        }
        checker.visit(node, &mut cx);
        open.push(node);
    }
    while let Some(top) = open.pop() {
        checker.leave(top, &mut cx);
    }
    checker.end_file(&mut cx);
    let mut diagnostics = cx.into_diagnostics();
    for diagnostic in &mut diagnostics {
        if diagnostic.severity.is_none() {
            diagnostic.severity = rules
                .iter()
                .find(|rule| rule.code == diagnostic.code)
                .map(|rule| rule.severity);
        }
    }
    diagnostics
}

#[doc(hidden)]
pub mod __export {
    use crate::bindings::exports::ferrolint::plugin::checker as raw;
    use crate::{Checker, File, Node};

    pub fn info<C: Checker>() -> raw::PluginInfo {
        C::info().into_raw()
    }

    pub fn check<C: Checker>(file: &File, nodes: &[Node]) -> Vec<raw::Diagnostic> {
        crate::run::<C>(file, nodes, &crate::context::HostSemantic)
            .into_iter()
            .map(crate::Diagnostic::into_raw)
            .collect()
    }
}

/// Export a [`Checker`] as the plugin's implementation of the contract. On
/// any target but `wasm32` it expands to nothing but a use of the type.
#[macro_export]
macro_rules! export_checker {
    ($checker:ty) => {
        #[cfg(target_arch = "wasm32")]
        const _: () = {
            struct Export;

            impl $crate::bindings::exports::ferrolint::plugin::checker::Guest for Export {
                fn info() -> $crate::bindings::exports::ferrolint::plugin::checker::PluginInfo {
                    $crate::__export::info::<$checker>()
                }

                fn check(
                    file: $crate::File,
                    nodes: ::std::vec::Vec<$crate::Node>,
                ) -> ::std::vec::Vec<
                    $crate::bindings::exports::ferrolint::plugin::checker::Diagnostic,
                > {
                    $crate::__export::check::<$checker>(&file, &nodes)
                }
            }

            $crate::bindings::export!(Export with_types_in $crate::bindings);
        };

        #[cfg(not(target_arch = "wasm32"))]
        const _: fn() -> $crate::Info = <$checker as $crate::Checker>::info;
    };
}

#[cfg(test)]
mod tests {
    #[test]
    fn the_sdk_version_is_the_contract_version() {
        let wit = include_str!("../../../wit/plugin.wit");
        let package = wit
            .lines()
            .find_map(|line| line.strip_prefix("package ferrolint:plugin@"))
            .and_then(|rest| rest.strip_suffix(';'))
            .unwrap();
        assert_eq!(package, super::CONTRACT_VERSION);
    }
}
