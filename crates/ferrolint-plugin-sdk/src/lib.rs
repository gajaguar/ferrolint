//! Guest-side SDK for ferrolint WASM plugins.
//!
//! A plugin is a [`Checker`]: it declares its rules, receives the visitor
//! events of each file in source order, asks the host scope and binding
//! questions through its [`Context`], and reports [`Diagnostic`]s. The
//! [`export_checker!`] macro turns it into a `wasm32-wasip2` component that
//! implements the `ferrolint:plugin` contract:
//!
//! ```ignore
//! use ferrolint_plugin_sdk::prelude::*;
//!
//! #[derive(Default)]
//! struct NoPrint;
//!
//! impl Checker for NoPrint {
//!     fn info() -> Info {
//!         Info::new("no-print", "0.1.0").rule(Rule::new("NP001", "print-call", "print() is called."))
//!     }
//!
//!     fn visit(&mut self, node: &Node, cx: &mut Context<'_>) {
//!         if node.kind == NodeKind::Name && node.name.as_deref() == Some("print") {
//!             cx.report(Diagnostic::new("NP001", "print() is called", node.range));
//!         }
//!     }
//! }
//!
//! export_checker!(NoPrint);
//! ```
//!
//! The SDK's version is the version of the WIT contract it wraps.

