def resolve(qualified):
    """The class named `qualified` and the node astroid builds for it."""
    module, _, name = qualified.rpartition(".")
    cls = getattr(importlib.import_module(module or "builtins"), name)
    # An alias (`IOError`, `socket.error`) is the class under its own name.
    tree = astroid.MANAGER.ast_from_module_name(cls.__module__)
    return next(tree.igetattr(cls.__name__))


def methods(cls):
    found = set()
    for klass in [cls, *cls.ancestors()]:
        if klass.name != "object":
            found.update(
                name
                for name, nodes_ in klass.locals.items()
                if isinstance(nodes_[0], nodes.FunctionDef)
            )
    return sorted(found)


version = ".".join(map(str, sys.version_info[:3]))
print(f"//! Generated by `tools/class-methods.py` from Python {version}; do not edit.\n")
print("/// The standard library classes with the methods each one and its ancestors")
print(f"/// define, as astroid builds them from Python {version}.")
print("pub const CLASS_METHODS: &[(&str, &[&str])] = &[")
for qualified in sorted(CLASSES):
    try:
        found = methods(resolve(qualified))
    except Exception as error:  # a class of another platform or version
        print(f"skipped {qualified}: {error}", file=sys.stderr)
        continue
    print(f'    ("{qualified}", &[')
    for item in found:
        print(f'        "{item}",')
    print("    ]),")
print("];\n")
print(
    "/// The methods `qualified` and its ancestors define, `None` when it is not listed.\n"
    "pub fn methods(qualified: &str) -> Option<&'static [&'static str]> {\n"
    "    CLASS_METHODS\n"
    "        .binary_search_by_key(&qualified, |(class, _)| class)\n"
    "        .ok()\n"
    "        .map(|at| CLASS_METHODS[at].1)\n"
    "}"
)
