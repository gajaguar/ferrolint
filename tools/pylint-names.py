"""Dump the names Pylint knows into crates/ferrolint/src/pylint_names.rs.

Run it with the Python of a virtualenv that has Pylint and pylint_django
installed (`make pylint-names PYTHON=...`). The extensions are loaded too, so a
name they own is never reported as unknown.
"""

import argparse
import importlib
import pkgutil
import sys

import pylint.extensions
from pylint.checkers import initialize
from pylint.lint import PyLinter
from pylint.message._deleted_message_ids import (
    DELETED_MESSAGES_IDS,
    MOVED_TO_EXTENSIONS,
)

linter = PyLinter()
initialize(linter)
# Pylint's own messages, before an extension or a plugin adds its own.
core = [
    (m.msgid, m.symbol, m.msgid, m.symbol, m.checker_name)
    for m in linter.msgs_store.messages
]
for m in linter.msgs_store.messages:
    core.extend((i, s, m.msgid, m.symbol, m.checker_name) for i, s in m.old_names)
extensions = [
    f"pylint.extensions.{m.name}"
    for m in pkgutil.iter_modules(pylint.extensions.__path__)
    if not m.name.startswith("_")
]
# Load each plugin on its own and attribute what it adds: message ids and
# symbols (old names too) and checker names. Core Pylint owns the rest.
plugins = {}
seen_messages = {id(m) for m in linter.msgs_store.messages}
seen_checkers = set(linter._checkers)
for module in extensions + ["pylint_django", "pylint_django.checkers.migrations"]:
    linter.load_plugin_modules([module])
    for message in linter.msgs_store.messages:
        if id(message) in seen_messages:
            continue
        for name in (message.msgid, message.symbol):
            plugins.setdefault(name, module)
        for pair in message.old_names:
            for name in pair:
                plugins.setdefault(name, module)
    for name in set(linter._checkers) - seen_checkers:
        plugins.setdefault(name, module)
    seen_messages = {id(m) for m in linter.msgs_store.messages}
    seen_checkers = set(linter._checkers)

options = set()
for group in linter._arg_parser._action_groups:
    if group.title in {"options", "optional arguments", "Commands", "positional arguments"}:
        continue
    for action in group._group_actions:
        options.update(o[2:] for o in action.option_strings if o.startswith("--"))

known = set()
for message in linter.msgs_store.messages:
    known.update((message.msgid, message.symbol))
    known.update(name for pair in message.old_names for name in pair)

deleted = set()
for entries in DELETED_MESSAGES_IDS.values():
    for entry in entries:
        deleted.update((entry.msgid, entry.symbol))
        deleted.update(name for pair in entry.old_names for name in pair)
deleted -= known

moved = set()
for entries in MOVED_TO_EXTENSIONS.values():
    for entry in entries:
        moved.update((entry.msgid, entry.symbol))
        moved.update(name for pair in entry.old_names for name in pair)


def emit(name, doc, values):
    print(f"/// {doc}")
    print(f"pub const {name}: &[&str] = &[")
    for value in sorted(values):
        print(f'    "{value}",')
    print("];\n")


print("//! Generated by `make pylint-names` from Pylint and `pylint_django`; do not edit.\n")
emit("OPTIONS", "Every option Pylint, its extensions and `pylint_django` accept.", options)
emit("CHECKERS", "The checker names, which `disable` and `enable` accept like a category.", linter._checkers)
emit("MESSAGES", "Every message id and symbol, current or legacy, sorted.", known)
emit("DELETED", "Message ids and symbols Pylint removed.", deleted)
emit("MOVED", "Message ids and symbols Pylint moved to an optional extension.", moved)
print("/// The plugin module a message or checker name belongs to; a name core")
print("/// Pylint owns has no entry. Sorted by name.")
print("#[rustfmt::skip]")
print("pub const PLUGIN_NAMES: &[(&str, &str)] = &[")
for name, module in sorted(plugins.items()):
    print(f'    ("{name}", "{module}"),')
print("];\n")
print("/// Pylint's own messages as `(id, symbol, current id, current symbol, checker)`;")
print("/// a legacy name has the current message's id and symbol after its own.")
print("#[rustfmt::skip]")
print("pub const CORE_MESSAGES: &[(&str, &str, &str, &str, &str)] = &[")
for row in sorted(core):
    print("    (" + ", ".join(f'"{v}"' for v in row) + "),")
print("];\n")
print(
    "/// Whether `name` is in the sorted `list`.\n"
    "pub fn contains(list: &[&str], name: &str) -> bool {\n"
    "    list.binary_search(&name).is_ok()\n"
    "}\n"
)
print(
    "/// The plugin module that owns `name`, if core Pylint does not.\n"
    "pub fn owner(name: &str) -> Option<&'static str> {\n"
    "    PLUGIN_NAMES\n"
    "        .binary_search_by(|(probe, _)| probe.cmp(&name))\n"
    "        .ok()\n"
    "        .map(|index| PLUGIN_NAMES[index].1)\n"
    "}"
)
