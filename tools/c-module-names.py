"""Dump the public names of the standard library's C and builtin modules into
crates/ferrolint/src/c_module_names.rs.

A module with no `.py` file (`math`, `itertools`, `sys`, ...) is not parsed by
Pylint but imported, and `from m import *` binds the names `dir(m)` lists that
do not start with an underscore. Run it with the interpreter whose standard
library should be described (`make c-module-names PYTHON=...`); the table is
that version's, and a module that cannot be imported there is left out.
"""

import importlib
import importlib.machinery
import sys

# Modules that exist to test the interpreter, not to be star-imported.
SKIP = ("_test", "xx", "_xx")


def has_source(name):
    spec = importlib.machinery.PathFinder.find_spec(name)
    return spec is not None and (spec.origin or "").endswith(".py")


modules = {}
for name in sorted(sys.stdlib_module_names):
    if name.startswith(SKIP) or has_source(name):
        continue
    try:
        module = importlib.import_module(name)
    except Exception:  # a module of another platform
        continue
    modules[name] = [n for n in dir(module) if not n.startswith("_")]

version = ".".join(map(str, sys.version_info[:3]))
print(f"//! Generated by `make c-module-names` from Python {version}; do not edit.\n")
print("/// The standard library modules with no source file, with their public names")
print(f"/// in `dir` order, as Python {version} lists them (another version differs).")
print("pub const C_MODULES: &[(&str, &[&str])] = &[")
for name, names in modules.items():
    print(f'    ("{name}", &[')
    for item in names:
        print(f'        "{item}",')
    print("    ]),")
print("];\n")
print(
    "/// The public names of the C or builtin module `name`, `None` when it is not one.\n"
    "pub fn names(name: &str) -> Option<&'static [&'static str]> {\n"
    "    C_MODULES\n"
    "        .binary_search_by_key(&name, |(module, _)| module)\n"
    "        .ok()\n"
    "        .map(|at| C_MODULES[at].1)\n"
    "}"
)
