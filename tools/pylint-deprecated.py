"""Dump Pylint's deprecation tables into crates/ferrolint/src/pylint_deprecated.rs.

Run it with the Python of a virtualenv that has Pylint installed
(`make pylint-deprecated PYTHON=...`). Pylint takes these tables from the
interpreter it runs on, and it only sees a deprecated name that astroid can
infer there, so the dump has two parts:

* the tables of `pylint.checkers.stdlib` and `pylint.checkers.imports`, copied
  as they are (a Python 2 table is dropped: Pylint never reads it);
* `ALIASES`, the public spellings (`asyncio.sleep`) that astroid infers to a
  name of a table (`asyncio.tasks.sleep`) on this interpreter. A table name
  that nothing infers to, like a function this Python removed, has none and is
  never reported, as in Pylint.
"""

import sys

from astroid import MANAGER, bases, extract_node, nodes
from astroid.exceptions import AstroidError
from pylint.checkers import imports, stdlib

KNOWN = (nodes.FunctionDef, nodes.ClassDef, nodes.Module, bases.Instance)


def since(version):
    return f"({version[0]}, {version[1]})"


def variants(dotted):
    """The spellings of `dotted` that skip middle components or a leading `_`."""
    parts = dotted.split(".")
    found = {dotted}
    for head in range(1, len(parts)):
        for tail in range(head, len(parts)):
            found.add(".".join(parts[:head] + parts[tail:]))
    for spelling in list(found):
        if spelling.startswith("_"):
            found.add(spelling.lstrip("_"))
        if spelling.startswith("builtins."):
            found.add(spelling[len("builtins.") :])
    return found


def infer(path):
    """The names astroid infers `path` to, once its module is imported."""
    parts = path.split(".")
    code = path
    for end in range(len(parts), 0, -1):
        module = ".".join(parts[:end])
        try:
            MANAGER.ast_from_module_name(module)
        except AstroidError:
            continue
        code = f"import {module}\n{path}"
        break
    try:
        node = extract_node(code + "  #@")
        return {r.qname() for r in node.infer() if isinstance(r, KNOWN)}
    except (AstroidError, AttributeError):
        return set()


def literal(value):
    return f'"{value}"'


def names(entries):
    return "&[" + ", ".join(literal(n) for n in sorted(entries)) + "]"


def table(name, doc, table, body):
    print(f"/// {doc}")
    print("#[rustfmt::skip]")
    print(f"pub const {name}: &[(Since, {body[0]})] = &[")
    for version, entries in table.items():
        print(f"    ({since(version)}, {body[1](entries)}),")
    print("];\n")


methods = stdlib.DEPRECATED_METHODS[3]
call_keys = set().union(*methods.values(), *stdlib.DEPRECATED_DECORATORS.values())
for args in stdlib.DEPRECATED_ARGUMENTS.values():
    call_keys.update(args)
prefixes = {
    name.rsplit(".", 1)[0]
    for names_ in stdlib.DEPRECATED_ATTRIBUTES.values()
    for name in names_
}

aliases = set()
for key in sorted(call_keys | prefixes):
    wanted = call_keys | prefixes
    for path in variants(key):
        aliases.update((path, qname) for qname in infer(path) & wanted)

version = ".".join(map(str, sys.version_info[:3]))
print(f"//! Generated by `make pylint-deprecated` from Pylint and Python {version}; do not edit.\n")
print("/// The `(major, minor)` a table entry applies from.")
print("pub type Since = (u32, u32);")
print("/// A list of names.")
print("pub type Names = &'static [&'static str];")
print("/// The `(position, name)` pairs of a function; the position is `None` for a keyword-only argument.")
print("pub type Arguments = &'static [(Option<u32>, &'static str)];\n")
print("/// The Python the aliases were inferred on, and the version Pylint's tables use\n/// when `py-version` is not set.")
print(f"pub const REFERENCE: Since = {since(sys.version_info)};\n")
table("MODULES", "Deprecated modules, by the version that deprecated them.", imports.DEPRECATED_MODULES, ("&[&str]", names))
table("METHODS", "Deprecated functions and methods, by qualified name.", methods, ("&[&str]", names))
table(
    "ARGUMENTS",
    "Deprecated arguments: a function and its `(position, name)` pairs (`None` for keyword-only).",
    stdlib.DEPRECATED_ARGUMENTS,
    (
        "&[(&str, Arguments)]",
        lambda entries: "&["
        + ", ".join(
            f"({literal(func)}, &["
            + ", ".join(f"({'None' if p is None else f'Some({p})'}, {literal(a)})" for p, a in args)
            + "])"
            for func, args in entries.items()
        )
        + "]",
    ),
)
table(
    "CLASSES",
    "Deprecated classes of a module, by the version that deprecated them, in Pylint's order:\n/// a later version replaces the whole entry of a module.",
    stdlib.DEPRECATED_CLASSES,
    (
        "&[(&str, Names)]",
        lambda entries: "&[" + ", ".join(f"({literal(m)}, {names(c)})" for m, c in entries.items()) + "]",
    ),
)
table("DECORATORS", "Deprecated decorators, by qualified name.", stdlib.DEPRECATED_DECORATORS, ("&[&str]", names))
table("ATTRIBUTES", "Deprecated attributes, by qualified name.", stdlib.DEPRECATED_ATTRIBUTES, ("&[&str]", names))
print("/// `(public spelling, qualified name)`, sorted: what astroid infers each spelling to.")
print("#[rustfmt::skip]")
print("pub const ALIASES: &[(&str, &str)] = &[")
for pair in sorted(aliases):
    print(f"    ({literal(pair[0])}, {literal(pair[1])}),")
print("];")
